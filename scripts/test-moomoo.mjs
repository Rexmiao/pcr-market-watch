import assert from 'node:assert/strict';
import {createMoomooClient,createMoomooClientFromStore,createMoomooLocalHandler,moomooTesting as t} from './moomoo-client.mjs';

const secret='test-secret-must-not-appear-in-arguments';
const calls=[];
const runner=async request=>{
  assert(!request.args.join(' ').includes(secret));
  assert.equal(request.environment.OPENAPI_HOST_APPKEY,secret);
  assert.equal(request.environment.OPENAPI_HOST_URL,'http://127.0.0.1:22222');
  assert.equal(request.args[0],'--raw');
  calls.push(request.args);
  const command=request.args[1];
  const data={subscribe:{},'get-basic-qot':{basic_qot_list:[{security:{market:11,code:'NVDA'},cur_price:165.05,update_time:'2026-11-24 16:00:00'}]},'get-kline':{kl_list:[{time:'2026-11-24',close_price:165.05}]},'get-option-expiration-date':{date_list:[{strike_time:'2026-11-27'}]},'get-option-chain':{option_chain:[]}}[command];
  assert(data,'Only the five allowed market-data commands may run');
  return {code:0,stdout:JSON.stringify({ret_type:0,err_code:0,ret_msg:'',s2c:data}),stderr:''};
};
const client=createMoomooClient({appKey:secret,runner});
const quotes=await client.quotes(['NVDA','US.SNDK','NVDA']);
assert.equal(quotes.data.basic_qot_list[0].cur_price,165.05);
assert.deepEqual(calls[0].slice(-2),['US.NVDA','US.SNDK']);
assert.equal(calls[0][1],'subscribe');
assert.equal(calls[1][1],'get-basic-qot');
await client.quotes(['NVDA','US.SNDK']);
assert.equal(calls.length,2,'Quote cache must avoid repeated subscriptions and calls');
await client.dailyKline('NVDA',{count:60});
assert.equal(calls.at(-2)[calls.at(-2).indexOf('--sub-type-list')+1],'kl_day');
assert.equal(calls.at(-1).at(-1),'US.NVDA');
assert(calls.at(-1).includes('--kl-type'));
assert.equal(calls.at(-1)[calls.at(-1).indexOf('--security')+1],'US.NVDA');
await client.optionExpirations('SNDK');
assert.equal(calls.at(-1).at(-1),'US.SNDK');
assert.equal(calls.at(-1)[calls.at(-1).indexOf('--owner')+1],'US.SNDK');
await client.optionChain('SNDK',{begin:'2026-11-24',end:'2026-12-24'});
assert.equal(calls.at(-1).at(-1),'US.SNDK');
assert.equal(calls.at(-1)[calls.at(-1).indexOf('--owner')+1],'US.SNDK');
assert.equal(client.status().connectionStatus,'connected');
assert(!JSON.stringify(client.status()).includes(secret));
assert.equal(t.hostAddress('127.0.0.1:22222'),'http://127.0.0.1:22222');
assert.throws(()=>t.hostAddress('https://example.com:22222'),/loopback/);
assert.throws(()=>t.hostAddress('http://127.0.0.1:22222/path'),/loopback/);
assert.throws(()=>t.symbolList('NVDA;echo bad'),/valid/);
assert.throws(()=>t.symbolList('HK.00700'),/U.S./);
assert.throws(()=>t.expirationRange('2026-11-24','2026-12-25'),/one calendar month/);
assert.throws(()=>t.expirationRange('2026-02-30','2026-03-01'),/valid expiration/);

const noKey=createMoomooClient({appKey:'',runner});
await assert.rejects(noKey.quotes('NVDA'),/not configured/);
const rejected=createMoomooClient({appKey:secret,runner:async()=>({code:0,stdout:JSON.stringify({ret_type:-1,ret_msg:'AppKey rejected: '+secret,err_code:1}),stderr:''})});
await assert.rejects(rejected.quotes('NVDA'),error=>!error.message.includes(secret)&&error.message.includes('[redacted]'));
const notSubscribed=createMoomooClient({appKey:secret,runner:async()=>({code:1,stdout:'',stderr:JSON.stringify({error:'business error ret_type=-1 err_code=-1002: 请先订阅Basic数据'})})});
await assert.rejects(notSubscribed.quotes('NVDA'),error=>error.code==='NOT_SUBSCRIBED');
const noPermission=createMoomooClient({appKey:secret,runner:async()=>({code:1,stdout:'',stderr:JSON.stringify({error:'当前没有美股期权行情权限'})})});
await assert.rejects(noPermission.optionExpirations('NVDA'),error=>error.code==='NO_PERMISSION');
const fromStore=await createMoomooClientFromStore({readCredentials:async()=>({appKey:secret,hostUrl:'http://127.0.0.1:22222'}),runner});
assert.equal(fromStore.status().configured,true);
const handle=createMoomooLocalHandler(client);
assert.equal((await handle(new Request('http://127.0.0.1:8765/api/providers/moomoo/status'))).status,200);
assert.equal((await handle(new Request('http://127.0.0.1:8765/api/providers/moomoo/quotes?symbols=NVDA',{method:'POST'}))).status,405);
assert.equal((await handle(new Request('http://127.0.0.1:8765/api/providers/moomoo/status',{headers:{Origin:'https://attacker.example'}}))).status,403);
assert.equal((await handle(new Request('http://127.0.0.1:8765/api/providers/moomoo/orders'))).status,404);
assert.equal(await handle(new Request('http://127.0.0.1:8765/api/watchlist-settings')),null);
console.log('PASS read-only moomoo command allowlist, environment-only credentials, subscriptions, argument ordering, quote cache, input/host validation, redaction, and local routes');
